import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { isUuidV4, paymentReference } from '../../srv/lib/payment/references';

describe('payment references', () => {
  describe('isUuidV4 (BR-12)', () => {
    it('accepts a valid lowercase UUID v4', () => {
      assert.equal(isUuidV4('7b0c2f1e-4a5d-4c3b-9e8f-1a2b3c4d5e6f'), true);
    });

    it('accepts a valid uppercase UUID v4', () => {
      assert.equal(isUuidV4('7B0C2F1E-4A5D-4C3B-9E8F-1A2B3C4D5E6F'), true);
    });

    it('accepts UUIDs generated by crypto.randomUUID()', () => {
      assert.equal(isUuidV4(randomUUID()), true);
    });

    it('rejects a UUID with a version other than 4', () => {
      assert.equal(isUuidV4('7b0c2f1e-4a5d-1c3b-9e8f-1a2b3c4d5e6f'), false);
    });

    it('rejects a UUID with an invalid variant', () => {
      assert.equal(isUuidV4('7b0c2f1e-4a5d-4c3b-7e8f-1a2b3c4d5e6f'), false);
    });

    it('rejects a UUID without hyphens', () => {
      assert.equal(isUuidV4('7b0c2f1e4a5d4c3b9e8f1a2b3c4d5e6f'), false);
    });

    it('rejects non-hexadecimal characters', () => {
      assert.equal(isUuidV4('7b0c2f1e-4a5d-4c3b-9e8f-1a2b3c4d5e6g'), false);
    });

    it('rejects surrounding whitespace', () => {
      assert.equal(isUuidV4(' 7b0c2f1e-4a5d-4c3b-9e8f-1a2b3c4d5e6f'), false);
    });

    it('rejects an empty string', () => {
      assert.equal(isUuidV4(''), false);
    });
  });

  describe('paymentReference (spec 5.3)', () => {
    it('builds PAY- plus the first 8 characters in uppercase', () => {
      assert.equal(paymentReference('3f2a9c1e-4a5d-4c3b-9e8f-1a2b3c4d5e6f'), 'PAY-3F2A9C1E');
    });

    it('gives the same result for an uppercase ID', () => {
      assert.equal(paymentReference('3F2A9C1E-4A5D-4C3B-9E8F-1A2B3C4D5E6F'), 'PAY-3F2A9C1E');
    });

    it('always has the shape PAY-XXXXXXXX for a random UUID', () => {
      assert.match(paymentReference(randomUUID()), /^PAY-[0-9A-F]{8}$/);
    });

    it('throws on an invalid ID', () => {
      // TODO: "bukan-uuid" → error
      assert.throws(() => paymentReference('invalid-uuid'));
    });
  });
});
